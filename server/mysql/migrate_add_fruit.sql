-- 娱乐「水果机」(Pixi WT kind=48)
CREATE TABLE IF NOT EXISTS `server_fruit_session` (
  `role_id` INT UNSIGNED NOT NULL,
  `credits` INT UNSIGNED NOT NULL DEFAULT 0,
  `win_chips` INT UNSIGNED NOT NULL DEFAULT 0,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`role_id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `server_fruit_config` (
  `id` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `enabled` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `currency_type` TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0=金币 1=酷宝',
  `credits_per_unit` INT UNSIGNED NOT NULL DEFAULT 10 COMMENT '每1金币/酷宝兑换游戏币',
  `min_insert` INT UNSIGNED NOT NULL DEFAULT 1,
  `max_insert` INT UNSIGNED NOT NULL DEFAULT 999,
  `bonus_chance` TINYINT UNSIGNED NOT NULL DEFAULT 8 COMMENT '送灯概率0-100',
  `bonus_extra_percent` TINYINT UNSIGNED NOT NULL DEFAULT 50 COMMENT '送灯额外+%%',
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `server_fruit_wheel` (
  `slot_index` TINYINT UNSIGNED NOT NULL COMMENT '0-23',
  `fruit_id` TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0=幸运 1=BAR..8=苹果',
  `multiplier` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `weight` SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`slot_index`)
) ENGINE=InnoDB;
